/**
 * Mirror of `src/blogs/contracts/common.py`.
 *
 * This directory is the ONLY place backend field names appear. Nothing above
 * it re-declares a shape or inlines an endpoint path, so when a contract moves
 * the compiler points at every call site.
 *
 * Two properties of the Python side that constrain everything here:
 *
 *   `extra="forbid"` — an unknown key in a request body is a 400, never an
 *   ignored field. Request types are exact; do not spread loose objects into
 *   them.
 *
 *   `frozen=True` — responses are immutable server-side, so they are `readonly`
 *   here. Python tuples serialise as JSON arrays, hence `readonly T[]`.
 */

/** Server-side ids are UUIDv7 strings. Branded so a slug cannot be passed
 *  where an id belongs — the two are not interchangeable and the interaction
 *  routes take ids while the article routes take slugs. */
export type Uuid = string & { readonly __brand?: "uuid" };

export type UserId = Uuid;
export type ActorId = Uuid;
export type BlogId = Uuid;
export type CommentId = Uuid;
export type CatalogId = Uuid;
export type PinId = Uuid;
export type SeriesId = Uuid;

/** Lowercase, hyphen-separated: `^[a-z0-9]+(-[a-z0-9]+)*$`. Category keys and
 *  blog slugs share this shape. */
export type KeyStr = string;

/** A heading anchor. Same shape as KeyStr but longer, and may carry a `-2`
 *  disambiguating suffix. Generated by the backend at publish time — never
 *  derive these on the client. */
export type AnchorStr = string;

/** ISO-8601 UTC, e.g. `2026-08-22T12:00:00Z`. One endpoint
 *  (`/auth/otp/request`) emits `+00:00` instead; `parseInstant` handles both. */
export type IsoDateTime = string;

