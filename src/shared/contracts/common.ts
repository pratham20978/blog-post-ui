/** Per-field detail attached to `REQUEST_INVALID`. Capped at 10 by the server,
 *  and it never echoes the submitted value. */
export interface FieldViolation {
  readonly field: string;
  readonly reason: string;
}

export interface ErrorEnvelope {
  readonly category: ErrorCategory;
  /** Safe to render verbatim — the server guarantees it leaks nothing. */
  readonly safe_message: string;
  readonly retryability: Retryability;
  readonly stage: ProcessingStage;
  readonly safe_details: Readonly<Record<string, unknown>> & {
    readonly fields?: readonly FieldViolation[];
    readonly reason?: string;
  };
  /** Echoed in the `X-Correlation-ID` header. Show it on error screens: it is
   *  what makes a user's report findable in the server logs. */
  readonly correlation_id: string;
}

/** Every route returns this, success or failure. */
export interface APIResponse<T> {
  readonly success: boolean;
  readonly message: string;
  readonly data: T | null;
  readonly error: ErrorEnvelope | null;
}

/**
 * Keyset pagination. There is no `page`, `offset` or `total` anywhere in this
 * API — the backend refuses OFFSET because it drifts on an append-heavy table.
 *
 * `next_cursor` is an opaque base64url blob. Never parse or construct one.
 */
export interface Page<T> {
  readonly items: readonly T[];
  readonly next_cursor: string | null;
  readonly has_more: boolean;
}
